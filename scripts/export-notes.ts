/**
 * `pnpm notes:md`: writes docs/presenter-script.md, every slide's speaker notes in talk order
 * (the default profile, then the slides only other profiles use), for reading and rehearsal.
 * Generated from src/slides/*.html, so edit the slides, not the output.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Window } from 'happy-dom';
import { manifest } from '../src/deck.ts';

const root = resolve(import.meta.dirname, '..');
const slidesDir = resolve(root, 'src/slides');
const window = new Window();
const document = window.document;

const slides = new Map<string, Element>();
for (const file of readdirSync(slidesDir)
  .filter((f) => f.endsWith('.html'))
  .sort()) {
  const template = document.createElement('template');
  template.innerHTML = readFileSync(resolve(slidesDir, file), 'utf8');
  const section = template.content.firstElementChild;
  const id = section?.getAttribute('data-id');
  if (section && id) slides.set(id, section as unknown as Element);
}

const text = (node: Element): string => (node.textContent ?? '').replace(/\s+/g, ' ').trim();

/** Notes HTML to Markdown: headings, step blocks, paragraphs and lists. */
function notesToMarkdown(aside: Element): string {
  const out: string[] = [];
  for (const child of Array.from(aside.children)) {
    const tag = child.tagName.toLowerCase();
    if (tag === 'h3') out.push(`#### ${text(child)}`);
    else if (tag === 'p') {
      const only = child.getAttribute('data-profile');
      out.push(only ? `_Only in the ${only} talk:_ ${text(child)}` : text(child));
    } else if (tag === 'ul' || tag === 'ol') {
      out.push(
        Array.from(
          child.children,
          (li, i) => `${tag === 'ol' ? `${i + 1}.` : '-'} ${text(li)}`,
        ).join('\n'),
      );
    } else if (child.hasAttribute('data-step')) {
      const step = child.getAttribute('data-step');
      const label = step === '0' ? 'As the slide appears' : `Step ${step}`;
      out.push(`**${label}.** ${Array.from(child.children, text).join(' ')}`);
    } else if (tag === 'div') {
      out.push(notesToMarkdown(child));
    }
  }
  return out.join('\n\n');
}

const profiles = Object.entries(manifest.profiles).sort(([a], [b]) =>
  a === manifest.defaultProfile ? -1 : b === manifest.defaultProfile ? 1 : 0,
);
const order = profiles
  .flatMap(([, entries]) => entries)
  .filter((e, i, all) => all.findIndex((f) => f.id === e.id) === i);
const fmt = (s: number) => `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
const planned = (entries: readonly { targetSeconds: number; backup?: boolean }[]) =>
  fmt(entries.filter((e) => !e.backup).reduce((t, e) => t + e.targetSeconds, 0));

const parts = [
  '# Presenter script',
  '',
  '_Generated by `pnpm notes:md` from `src/slides/*.html`. Do not edit by hand._',
  '',
  `${profiles.map(([name, entries]) => `${name} talk ${planned(entries)}`).join(', ')}.`,
];
for (const entry of order) {
  const section = slides.get(entry.id);
  if (!section) continue;
  const heading = section.querySelector('h1, h2');
  const where = profiles.flatMap(([name, entries]) => {
    const i = entries.findIndex((e) => e.id === entry.id);
    const e = entries[i];
    return e ? [`${name} #${i + 1} (${fmt(e.targetSeconds)}${e.backup ? ', backup' : ''})`] : [];
  });
  parts.push(
    '',
    '---',
    '',
    `## ${heading ? text(heading) : entry.id}`,
    '',
    `_${where.join(' · ')}_`,
  );
  const aside = section.querySelector('aside.notes');
  if (aside) parts.push('', notesToMarkdown(aside));
}
const target = resolve(root, 'docs/presenter-script.md');
writeFileSync(target, `${parts.join('\n')}\n`);
console.log(`wrote ${target}`);
await window.happyDOM.close();
